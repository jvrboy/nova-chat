-- ============ TRIGGERS ============
create or replace function touch_updated_at() returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

drop trigger if exists trg_chats_touch on chats;
create trigger trg_chats_touch before update on chats for each row execute function touch_updated_at();

drop trigger if exists trg_messages_touch on messages;
create trigger trg_messages_touch before update on messages for each row execute function touch_updated_at();

drop trigger if exists trg_artifacts_touch on artifacts;
create trigger trg_artifacts_touch before update on artifacts for each row execute function touch_updated_at();

drop trigger if exists trg_settings_touch on user_settings;
create trigger trg_settings_touch before update on user_settings for each row execute function touch_updated_at();

-- ============ HELPER: get_or_create_default_user ============
create or replace function get_or_create_default_user() returns uuid as $$
declare
  uid uuid;
begin
  select id into uid from user_profiles where email = 'default@nova-chat.local' limit 1;
  if uid is null then
    insert into user_profiles (email, display_name)
    values ('default@nova-chat.local', 'Default User')
    returning id into uid;
    insert into user_settings (user_id) values (uid);
  end if;
  return uid;
end;
$$ language plpgsql;
